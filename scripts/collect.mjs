import { runCollection } from './runner.mjs';
import { toPayload, sqlLiteral } from './collectors.mjs';
import { writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
const output=process.argv[2];
if(!output) throw new Error('Usage: npm run collect -- /tmp/stockagentai-import.sql');
const runKey='manual-'+randomUUID();
const results=await runCollection({runKey});
const statements=results.map(r=>'select public.record_ingestion('+sqlLiteral(JSON.stringify(toPayload(r,runKey)))+'::jsonb);');
await writeFile(output,'begin;\n'+statements.join('\n')+'\ncommit;\n',{mode:0o600});
for(const r of results)console.log(`${r.id}: ${r.error || 'success'}; ${r.candidates.length} candidates`);
console.log(`Reviewable SQL saved to ${output}`);
if(results.some(r=>r.error))process.exitCode=1;
